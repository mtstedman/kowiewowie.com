import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {verifyPackage,canonical} from '../htdocs/games/arcade/package-contract.mjs';
import {validateBinding} from '../htdocs/games/netplay/policy.mjs';
const root=path.resolve(fileURLToPath(new URL('../',import.meta.url)));
const read=url=>fs.readFileSync(path.join(root,'htdocs',url));
const sha=b=>createHash('sha256').update(b).digest('hex');
const catalog=JSON.parse(read('/games/arcade/catalog.json'));
const entries=catalog.map(r=>({row:r,envelope:JSON.parse(read(r.manifest))})).filter(x=>x.envelope.manifest.platform==='SNES');
test('SNES packages authenticate ROM, shared core, inventories and network control descriptors',async()=>{
 assert(entries.length>=2,'Existing SNES packages must remain registered');
 const network=JSON.parse(read('/games/netplay/catalog.json'));
 for(const {row,envelope}of entries){
  const p=await verifyPackage(envelope,row.artifactDigest),cart=JSON.parse(read(p.route+'cartridge.json'));
  assert.equal(cart.format,'snes-cartridge/1');assert.equal(cart.id,p.id);
  const rom=read(p.route+'source.sfc');assert.equal(sha(rom),cart.metadata.romSha256);assert.equal(rom.length,cart.metadata.romBytes);
  for(const [url,pin]of Object.entries(p.files)){const b=read(url);assert.equal(b.length,pin.bytes,url);assert.equal(sha(b),pin.sha256,url);}
  for(const file of ['posse-snes.cjs','posse-snes.wasm','runner.mjs','worker.mjs','LICENSE','NOTICE'])assert(p.files['/games/engines/snes/'+file]);
  assert.equal(p.inputs.length,12);assert.deepEqual(new Set(p.inputs.map(i=>i.id)),new Set(['a','b','x','y','l','r','start','select','up','down','left','right']));
  if(cart.sharing===false){assert.equal(network.packages[p.id],undefined);assert.equal(p.capabilities.play,'none');assert.equal(p.capabilities.watch,false);}
  else{const binding=validateBinding(network.packages[p.id]);assert.equal(binding.artifactDigest,p.artifactDigest);assert.equal(binding.inputsDigest,sha(canonical(p.inputs.map(({id,label,kind})=>({id,label,kind})))));assert.equal(binding.capabilities.nativePlayers,cart.nativePlayers);assert.equal(p.capabilities.play,cart.nativePlayers===2?'host-p1-guest-p2':'shared-hero');}
  assert.equal(p.capabilities.nativePlayers,cart.nativePlayers);
  assert.equal(p.capabilities.mode,cart.nativePlayers===2?'alternating':'solo');
  const alias=read(p.route+'index.html').toString();assert(alias.includes('content="0;url=/games/arcade/?package='+p.id+'"'));assert(alias.includes('href="/games/arcade/?package='+p.id+'"'));assert(!alias.includes('<script'));
 }
});
test('all SNES games share one maintained core instead of per-title engines',()=>{
 const digests=entries.map(({envelope:{manifest:p}})=>p.files['/games/engines/snes/posse-snes.wasm'].sha256);
 assert.equal(new Set(digests).size,1);
 for(const {envelope:{manifest:p}}of entries)assert(!Object.keys(p.files).some(url=>url.startsWith(p.route)&&url.endsWith('.wasm')));
});
